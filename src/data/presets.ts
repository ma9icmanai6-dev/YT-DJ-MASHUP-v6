/**
 * Picks a random True Mashup pairing (Top Acapella + Top Instrumental)
 * ensuring it never repeats the exact same pairing twice in a row and guarantees
 * Songs, Lyrics, and Beats compatibility.
 */
export function getRandomCompatMashupPairing(lastPairingId?: string) {
  const candidates = TRUE_MASHUP_STEM_PAIRINGS.filter(p => p.id !== lastPairingId);
  const pool = candidates.length > 0 ? candidates : TRUE_MASHUP_STEM_PAIRINGS;
  const chosen = pool[Math.floor(Math.random() * pool.length)];
  return chosen;
}

